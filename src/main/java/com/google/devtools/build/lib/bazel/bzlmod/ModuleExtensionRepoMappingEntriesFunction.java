package com.google.devtools.build.lib.bazel.bzlmod;

import com.google.common.collect.ImmutableList;
import com.google.common.collect.ImmutableMap;
import com.google.devtools.build.lib.bazel.bzlmod.ModuleExtensionRepoMappingEntriesValue.Entries;
import com.google.devtools.build.lib.cmdline.RepositoryMapping;
import com.google.devtools.build.lib.cmdline.RepositoryName;
import com.google.devtools.build.lib.skyframe.RepositoryMappingValue;
import com.google.devtools.build.skyframe.SkyFunction;
import com.google.devtools.build.skyframe.SkyKey;
import com.google.devtools.build.skyframe.SkyValue;
import java.util.HashMap;
import javax.annotation.Nullable;

/**
 * A SkyFunction that computes the {@link RepositoryMapping#entries()} for the repos generated by a
 * module extension. While the repos differ in {@link RepositoryMapping#contextRepo()}, the entries
 * are identical and sharing the instance ensures that memory and CPU usage are only linear in the
 * number of repos.
 */
public class ModuleExtensionRepoMappingEntriesFunction implements SkyFunction {

  @Override
  @Nullable
  public SkyValue compute(SkyKey skyKey, Environment env) throws InterruptedException {
    BazelDepGraphValue bazelDepGraphValue =
        (BazelDepGraphValue) env.getValue(BazelDepGraphValue.KEY);
    if (bazelDepGraphValue == null) {
      return null;
    }

    var moduleExtensionId = ((ModuleExtensionRepoMappingEntriesValue.Key) skyKey).argument();
    var extensionEvalValue =
        (SingleExtensionValue) env.getValue(SingleExtensionValue.key(moduleExtensionId));
    var moduleRepoMapping =
        (RepositoryMappingValue)
            env.getValue(
                RepositoryMappingValue.key(moduleExtensionId.bzlFileLabel().getRepository()));
    if (env.valuesMissing()) {
      return null;
    }

    return computeRepoMappingEntries(
        moduleExtensionId,
        extensionEvalValue,
        bazelDepGraphValue,
        moduleRepoMapping.repositoryMapping());
  }

  /**
   * Calculates the shared default mapping and any explicitly scoped sibling mappings. All generated
   * repositories inherit the host module's visible repositories.
   */
  private ModuleExtensionRepoMappingEntriesValue computeRepoMappingEntries(
      ModuleExtensionId extensionId,
      SingleExtensionValue extensionEvalValue,
      BazelDepGraphValue bazelDepGraphValue,
      RepositoryMapping moduleRepoMapping) {
    // Find the key of the module containing this extension. This will be used to compute additional
    // mappings -- any repo generated by an extension contained in the module "foo" can additionally
    // see all repos that "foo" can see.
    ModuleKey moduleKey =
        bazelDepGraphValue
            .getCanonicalRepoNameLookup()
            .get(extensionId.bzlFileLabel().getRepository());
    // NOTE(wyv): This means that if "foo" has a bazel_dep with the repo name "bar", and the
    // extension generates an internal repo name "bar", then within a repo generated by the
    // extension, "bar" will refer to the latter. We should explore a way to differentiate between
    // the two to avoid any surprises.
    // LINT.IfChange
    ImmutableMap.Builder<String, RepositoryName> entries = ImmutableMap.builder();
    entries.putAll(moduleRepoMapping.entries());
    entries.putAll(extensionEvalValue.canonicalRepoNameToInternalNames().inverse());
    entries.putAll(bazelDepGraphValue.getRepoOverrides().row(extensionId));
    var builtEntries = entries.buildKeepingLast();
    // LINT.ThenChange(//src/main/java/com/google/devtools/build/lib/bazel/bzlmod/ModuleExtensionEvalStarlarkThreadContext.java)
    var bySiblings = new HashMap<ImmutableList<String>, Entries>();
    var byRepo = ImmutableMap.<RepositoryName, Entries>builder();
    var repoNames = extensionEvalValue.canonicalRepoNameToInternalNames().inverse();
    for (var entry : extensionEvalValue.generatedRepoSpecs().entrySet()) {
      var siblings = entry.getValue().visibleSiblings();
      if (siblings != null) {
        var scoped =
            bySiblings.computeIfAbsent(
                siblings, names -> restrict(moduleRepoMapping.entries(), builtEntries, names));
        byRepo.put(repoNames.get(entry.getKey()), scoped);
      }
    }
    return new ModuleExtensionRepoMappingEntriesValue(
        Entries.of(builtEntries), byRepo.buildOrThrow(), moduleKey);
  }

  private static Entries restrict(
      ImmutableMap<String, RepositoryName> host,
      ImmutableMap<String, RepositoryName> all,
      ImmutableList<String> allowed) {
    var entries = ImmutableMap.<String, RepositoryName>builder().putAll(host);
    for (String sibling : allowed) {
      var target = all.get(sibling);
      if (target != null) {
        entries.put(sibling, target);
      }
    }
    return Entries.of(entries.buildKeepingLast());
  }
}
